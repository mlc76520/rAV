//! Frequency band tables (the C++ version's calibration).

pub struct FreqBand {
    pub low: u32,
    pub high: u32,
    pub correction: f32,
}

const fn b(low: u32, high: u32, correction: f32) -> FreqBand {
    FreqBand { low, high, correction }
}

